/**
 * The icon for a callout kind, drawn in the heading's text colour. A kind
 * nobody knows gets the note icon, just as it gets the note colour. The
 * icon carries the kind's name as its accessible label and hover text, since
 * a custom title hides that name from the heading.
 */
export function calloutIcon(kind: string): SVGSVGElement {
  const known = (CALLOUT_KINDS as readonly string[]).includes(kind);
  const paths = CALLOUT_ICON_PATHS[(known ? kind : "note") as CalloutKind];
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("class", "cm-typst-callout-icon");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "2");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("role", "img");
  svg.innerHTML = paths; // static-only: fixed icon drawings above, never user text
  const name = calloutKindLabel(kind);
  svg.setAttribute("aria-label", name);
  const title = document.createElementNS("http://www.w3.org/2000/svg", "title");
  title.textContent = name;
  svg.prepend(title);
  return svg;
}
